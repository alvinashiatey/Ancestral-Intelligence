		<p>
			This hybrid studio-seminar course examines the life of objects across time, institutions, and
			lived contexts through hands-on engagement, critical reading, and experimental making. Working
			with objects from the university’s collection and installations at the Yale University Art
			Gallery, students investigate how meaning is produced, transformed, and contested through
			display, interpretation, and use. The Nguni exhibition anchors the course, framing questions
			of cultural authorship, material knowledge, and representation through the lens of situated
			knowledge.
		</p>
		<p>
			Using lens-based and technological tools, such as 3D scanning, microscopy, and imaging
			techniques, students encounter objects anew and consider how mediation reshapes perception and
			knowledge. The course emphasizes multisensory approaches and diverse interpretive frameworks,
			with particular attention to “charged objects” and the ethics of access, display, and use.
		</p>
		<p>
			Foregrounding multiple methodologies of “listening to images”, including close looking,
			sensory analysis, studio production, discussion, and writing, the course bridges analysis and
			making. Guest speakers, including international practitioners, curators, conservators, and
			scholars, contribute to the course, alongside artist-led workshops that examine connections
			between making, labor, craft traditions, and embodied knowledge, foregrounding practitioners
			as keepers of technique and cultural memory.
		</p>
	</article>
</section>

